// Icons are SVG paths from @mdi/js, not the 400 KB MDI web font (2026-11-23, performance review).
// This script finds every "mdi-xxx" name used in src/ and writes src/plugins/icons.generated.ts,
// so only those icons end up in the bundle. It runs before dev and build; `--check` fails if the file is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as mdi from '@mdi/js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');
const out = path.join(src, 'plugins', 'icons.generated.ts');

const names = new Set();
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(vue|ts)$/.test(e.name) && p !== out) {
      for (const m of fs.readFileSync(p, 'utf8').matchAll(/(?<![\w/.-])mdi-[a-z0-9]+(?:-[a-z0-9]+)*/g)) names.add(m[0]);
    }
  }
})(src);

const toExport = (n) => n.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const sorted = [...names].sort();
const missing = sorted.filter((n) => !(toExport(n) in mdi));
if (missing.length) {
  console.error(`Unknown MDI icon names: ${missing.join(', ')}`);
  process.exit(1);
}
const body = `// GENERATED by scripts/gen-icons.mjs from the "mdi-xxx" names used in src/. Do not edit.
import { ${sorted.map(toExport).join(', ')} } from '@mdi/js';

export const ICON_PATHS: Record<string, string> = {
${sorted.map((n) => `  '${n}': ${toExport(n)},`).join('\n')}
};
`;
const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('src/plugins/icons.generated.ts is out of date: run `npm run icons`.');
    process.exit(1);
  }
} else if (current !== body) {
  fs.writeFileSync(out, body);
  console.log(`icons: ${sorted.length} icons`);
}
