// Builds docs/supabase-init.sql: ONE script to paste into the Supabase SQL Editor on an empty database
// (2026-11-25). It creates the tables in their FINAL shape straight from schema.prisma (no replay of old
// migrations that create and later drop tables), then the Data API lock, then records every migration in
// "_prisma_migrations" with the checksum Prisma computes, so the api's `prisma migrate deploy` skips them.
// Run after adding a migration:  npm run sql:supabase
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const apiDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migDir = path.join(apiDir, 'prisma', 'migrations');
const out = path.resolve(apiDir, '..', 'docs', 'supabase-init.sql');
/** Migrations with SQL that schema.prisma cannot express: their body is added after the tables. */
const RAW_SQL = ['_lock_public_tables'];

const names = fs
  .readdirSync(migDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(migDir, d.name, 'migration.sql')))
  .map((d) => d.name)
  .sort();
const read = (name) => fs.readFileSync(path.join(migDir, name, 'migration.sql'));
const lf = (buf) => buf.toString('utf8').replace(/\r\n/g, '\n').trimEnd();

const prismaBin = path.join(apiDir, 'node_modules', 'prisma', 'build', 'index.js');
const tables = execFileSync(process.execPath, [prismaBin, 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.prisma', '--script'], {
  cwd: apiDir,
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
})
  .replace(/\r\n/g, '\n')
  .replace(/^CREATE SCHEMA IF NOT EXISTS "public";\n+/m, '') // Supabase already has it
  .trimEnd();
if (!tables.includes('CREATE TABLE')) throw new Error('prisma migrate diff returned no tables');

const raw = names.filter((n) => RAW_SQL.some((s) => n.endsWith(s)));
const records = names.map((n) => {
  const checksum = crypto.createHash('sha256').update(read(n)).digest('hex');
  return `('${crypto.randomUUID()}', '${checksum}', now(), '${n}', now(), 1)`;
});

const sql = `-- Online Training: create every table on an EMPTY Supabase database.
-- Generated by api/scripts/build-supabase-sql.mjs from schema.prisma (${names.length} migrations, last: ${names.at(-1)}).
-- Supabase: SQL Editor -> New query -> paste this WHOLE file -> Run (nothing highlighted). Run it once only.
-- Optional: the api also creates the tables by itself on its first deploy (prisma migrate deploy).
-- Running this first is fine: the migrations are recorded in "_prisma_migrations", so the api skips them.

BEGIN;

DO $guard$
BEGIN
  IF to_regclass('public."User"') IS NOT NULL OR to_regclass('public."_prisma_migrations"') IS NOT NULL THEN
    RAISE EXCEPTION 'The tables already exist. This script is only for an empty database.';
  END IF;
END
$guard$;

SET LOCAL search_path TO public;

-- ===================== Tables (final shape, from schema.prisma) =====================
${tables}

${raw.map((n) => `-- ===================== ${n} =====================\n${lf(read(n))}`).join('\n\n')}

-- ===================== Prisma migration history =====================
CREATE TABLE "_prisma_migrations" (
    "id"                    VARCHAR(36) PRIMARY KEY NOT NULL,
    "checksum"              VARCHAR(64) NOT NULL,
    "finished_at"           TIMESTAMPTZ,
    "migration_name"        VARCHAR(255) NOT NULL,
    "logs"                  TEXT,
    "rolled_back_at"        TIMESTAMPTZ,
    "started_at"            TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count"   INTEGER NOT NULL DEFAULT 0
);
ALTER TABLE "_prisma_migrations" ENABLE ROW LEVEL SECURITY;

INSERT INTO "_prisma_migrations" ("id", "checksum", "finished_at", "migration_name", "started_at", "applied_steps_count") VALUES
${records.join(',\n')};

COMMIT;
`;

fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${names.length} migrations)`);
